"""Write the app's copy of the measured error bands (app/ui/js/accuracy_bands.js).

The table lives in ``src/vessel_reconstruction/accuracy_bands.py``; the app is plain JavaScript and
cannot import Python, so it reads this generated file. A test fails when the file is out of date.

    PYTHONPATH=src python scripts/export_accuracy_bands.py
"""
from __future__ import annotations

import json
from pathlib import Path

from vessel_reconstruction.accuracy_bands import bands_as_dicts

TARGET = Path(__file__).resolve().parents[1] / "app" / "ui" / "js" / "accuracy_bands.js"
HEADER = ("// Generated by scripts/export_accuracy_bands.py from src/vessel_reconstruction/accuracy_bands.py.\n"
          "// Do not edit by hand: edit the Python table, then run the script. A test checks this file.\n")


def render() -> str:
    return f"{HEADER}export const BANDS = {json.dumps(bands_as_dicts(), indent=2, ensure_ascii=False)};\n"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8")
    print(f"wrote {TARGET}")
