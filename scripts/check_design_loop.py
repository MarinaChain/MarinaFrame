"""Replay the plumbing gate using public particulars and a public retained parent.

The fleet and engineering coefficients are explicitly synthetic. This does not
check ship-design accuracy. Input parent.json is generated by the existing
public KVLCC2 sampler; no private ship data is read.
"""
import argparse
from copy import deepcopy
from dataclasses import asdict
import json
from pathlib import Path

from vessel_reconstruction.design_loop import create_record, run_pipeline
from vessel_reconstruction.hull_variation import HullSections, section_properties

PUBLIC_REQUIREMENT = 'https://www.ardmoreshipping.com/s/Ardmore-Gibraltar_q88_02Sep2025.pdf'
PARENT_SOURCE = 'https://simman2020.kr/contents/Ship_data_summary.php'


def gate_config(parent):
    cb, _ = section_properties(HullSections(**parent))
    # The public owner Q88 gives summer DWT 49,999 t (p3), Lpp 174 m,
    # beam 32.2 m, depth 19.1 m (p2), laden economical speed 11.75 kn (p20).
    # Only DWT and speed are requirements. Geometry below is a synthetic
    # constant-dimension fit sized to keep the retained parent's Cb reachable.
    fleet = [dict(ship_id=f'synthetic-plumbing-{i}', design_id=f'synthetic-plumbing-{i}',
        dwt_t=dwt, lpp_m=174., beam_m=32.2, draft_m=13.283, depth_m=19.1, cb=cb,
        sources=['synthetic constant-dimension plumbing fleet; not public regression data'])
        for i, dwt in enumerate((30000., 40000., 60000., 80000.))]
    return dict(design_id='public-product-tanker-plumbing', name='Public requirement plumbing demonstrator',
        sources=[PUBLIC_REQUIREMENT, 'Synthetic engineering assumptions; no accuracy claim'],
        requirements=dict(dwt_t=49999., service_speed_kn=11.75, cargo_types=['product oil']),
        fleet=fleet, parent=parent, parent_sources=[PARENT_SOURCE,
            'Retained length 263.999981 m; bottom 0.5 m and end regions omitted; planar end caps'],
        arrangement=dict(cargo_rows=3, cargo_columns=2, engine_room_length_m=25., forepeak_length_m=10.,
            slop_length_m=6., slop_columns=2, fuel_reserve_length_m=5.),
        weights=dict(narrow_house_lh_m2=200., wide_house_lh_m2=100., steel_coefficient=.03,
            outfit_t_m2=.3, machinery_rest_coefficient=.72, main_engine_mass_t=250., mcr_kw=10000.,
            component_cg_m=[[87., 0., 9.], [90., 0., 15.], [20., 0., 5.]],
            component_relative_bands=[.2, .25, .3], band_basis='synthetic sensitivity assumptions'),
        power=dict(water_density_kg_m3=1025., kinematic_viscosity_m2_s=1.19e-6,
            thrust_deduction=.2, wake_fraction=.3, open_water_efficiency=.65,
            relative_rotative_efficiency=1., shaft_efficiency=.98),
        engine=dict(rpm=80., sea_margin=.15, minimum_engine_margin=.05, maximum_engine_margin=.95,
            layouts=[dict(name='synthetic tuning', vertices=[[60., 500.], [100., 500.], [100., 20000.], [60., 20000.]],
                sfoc_by_load=[[.05, 185.], [.5, 175.], [.75, 170.], [1., 180.]],
                sources=['synthetic selected-rating table; not maker data'], sfoc_rating_kw=10000., sfoc_rating_rpm=80.)]),
        efficiency=dict(reference_speed_kn=10., auxiliary_sfoc_g_kwh=190., main_fuel='HFO', auxiliary_fuel='MDO',
            distance_nm=40000., fuel_t=[['HFO', 3000.]], year=2026,
            sources=['synthetic annual operation and reference-power speed; not a regulatory technical file']))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--parent', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    config = gate_config(json.loads(args.parent.read_text()))
    (args.out / 'config.json').write_text(json.dumps(config, indent=2))
    base, first = run_pipeline(create_record(config), args.out / 'cache')
    base.save(args.out / 'record.json')
    repeated, second = run_pipeline(create_record(config), args.out / 'cache')
    assert repeated.to_json() == base.to_json()
    assert second.executed == ()
    changed = deepcopy(config)
    changed['requirements']['service_speed_kn'] = 12.
    varied, third = run_pipeline(create_record(changed), args.out / 'cache')
    varied.save(args.out / 'changed-record.json')
    assert third.executed == ('concept', 'power', 'engine', 'efficiency')
    result = dict(first=asdict(first), identical=asdict(second), speed_changed=asdict(third),
        status='draft', accuracy_claim=False, sources=[PUBLIC_REQUIREMENT, PARENT_SOURCE],
        limits=['Synthetic fleet, weight coefficients, engine table and operating assumptions.',
                'Scaled trimmed KVLCC2 demonstrator, not a complete product-tanker hull.',
                'Public DWT and service speed do not establish a feasible design.'])
    (args.out / 'gate.json').write_text(json.dumps(result, indent=2))
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
